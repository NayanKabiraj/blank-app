"""Turns a list of authored scene lines (narration + a one-line visual description per scene -
written by whoever is preparing the topic, the same way shorts/ scripts are hand-written by a
researching Claude session, not auto-generated by a template) into the saved script.md file
and a timing-checked word count. `english_generator`/`hindi_generator` are thin, language-aware
wrappers around this shared writer.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import List

from .duration_controller import beat_for_second, check_duration

ROOT = Path(__file__).resolve().parents[3]


@dataclass
class ScriptLine:
    scene_id: str
    start: float
    end: float
    narration: str
    visual: str
    sources: List[str] | None = None


def word_count(lines: List[ScriptLine]) -> int:
    return sum(len(l.narration.split()) for l in lines)


def render_markdown(topic: str, lang: str, lines: List[ScriptLine]) -> str:
    out = [f"# {topic}", "", f"Language: `{lang}`", ""]
    out.append("| Scene | Time | Beat | Narration | Visual |")
    out.append("|---|---|---|---|---|")
    for l in lines:
        beat = beat_for_second(l.start)
        out.append(f"| {l.scene_id} | {l.start:.1f}-{l.end:.1f}s | {beat} | {l.narration} | {l.visual} |")
    wc = word_count(lines)
    check = check_duration(wc, lang)
    out += ["", f"Word count: {wc} ({check.message})"]
    sources = sorted({s for l in lines for s in (l.sources or [])})
    if sources:
        out += ["", "## Sources", *[f"- {s}" for s in sources]]
    return "\n".join(out) + "\n"


def write_script(topic_id: str, topic: str, lang: str, lines: List[ScriptLine], root: Path = ROOT) -> Path:
    out_dir = root / "content" / "scripts" / topic_id
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{lang}_script.md"
    path.write_text(render_markdown(topic, lang, lines), encoding="utf-8")
    return path
